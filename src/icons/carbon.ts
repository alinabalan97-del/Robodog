/**
 * src/icons/carbon.ts
 *
 * ── THE ICON MAP ───────────────────────────────────────────────────────────
 * Single source of truth for every icon in the app. Screens and config objects
 * reference a SEMANTIC KEY ('medication', 'overdue'), never a vendor icon name —
 * so re-pointing an icon, or swapping icon libraries again, is a one-line change
 * here instead of a find-and-replace across 19 files.
 *
 * Two groups:
 *   appIcons     — the app's own vocabulary (nav, clinical, commerce, status…).
 *   vuetifyAliases — Vuetify's INTERNAL slots (checkboxOn, prev, ratingFull…).
 *                  Vuetify renders these itself for v-checkbox, v-pagination,
 *                  v-rating, v-select, etc. They must all be present or those
 *                  components render nothing. The Carbon choices are lifted from
 *                  Vuetify's own iconsets/carbon.js, which picks via UnoCSS
 *                  classes (`i-carbon:*`); this project has no UnoCSS, so the
 *                  same choices resolve through @carbon/icons-vue components.
 *
 * WHY THE `24` VARIANTS: Carbon ships each glyph at 16/20/24/32. 24 is Vuetify's
 * default icon size, so at default density the glyph is pixel-exact. AppIcon then
 * renders it at width/height 1em, so Vuetify's existing font-size-based sizing
 * (`size="small"`, `size="32"`, surrounding font-size) keeps driving the real
 * size exactly as the MDI webfont did. Carbon svgs carry fill="currentColor", so
 * every existing color class / `color` prop keeps working untouched.
 */

